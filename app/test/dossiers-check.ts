import assert from 'node:assert/strict';
const store = await import('../src/dossiers.ts').catch(() => ({})) as Record<string, any>;
assert.equal(typeof store.parsePreferences, 'function', 'Secure dossier index missing');
const base = 'https://one.example', other = 'https://two.example', key = 'ab'.repeat(32);
const auth = (id: string) => ({session_id: id, token: 'fixture-token-' + id, device_id: key});
const old = store.parsePreferences(JSON.stringify({base, credentials: auth('old')}), base, key);
assert.equal(old.dossiers.length, 1);
assert.equal(old.dossiers[0].created_at, null, 'Legacy time unknown, not migration time');
let disk = JSON.stringify(old), current = old;
const write = async (value: string) => { disk = value; };
current = await store.savePreferences(current, base, auth('new'), key, write, '2026-11-14T00:00:00.000Z');
assert.deepEqual(current.dossiers.map((d: any) => d.session_id), ['old', 'new']);
assert.equal(JSON.parse(disk).dossiers[0].token, auth('old').token);
const before = JSON.stringify(current);
await assert.rejects(store.savePreferences(current, base, auth('failed'), key, async () => {throw new Error('native failure');}), /storage_error/);
assert.equal(JSON.stringify(current), before, 'Save failure must not mutate old references');
assert.equal(disk, before);
current = await store.savePreferences(current, other, null, key, write);
assert.equal(current.credentials, null, 'Host change never reuses bearer');
assert.equal(current.dossiers.length, 2, 'Host change retains all references');
assert.equal(store.dossiersForBase(current, other).length, 0);
assert.equal(store.dossiersForBase(current, base).length, 2);
await assert.rejects(store.savePreferences(current, other, auth('old'), key, write), /storage_error/, 'Cannot select credentials from wrong host');
current = await store.savePreferences(current, base, auth('old'), key, write);
assert.equal(current.credentials.session_id, 'old');
assert.equal(current.dossiers.length, 2);
assert.equal(current.dossiers[0].created_at, null, 'Selection does not invent date');
for (const bad of [{...old, dossiers: [{...old.dossiers[0], device_id: 'cd'.repeat(32)}]}, {...old, dossiers: [...old.dossiers, old.dossiers[0]]}, {...old, unexpected: 'must not silently discard'}]) assert.throws(() => store.parsePreferences(JSON.stringify(bad), base, key), /storage_error/);
// Realistic UUID / URL-safe 43-char bearer fixture. Entire canonical value stays below conservative native limit.
let bounded = store.parsePreferences(null, base, key);
for (let n = 0; n < store.MAX_DOSSIERS; n++) bounded = await store.savePreferences(bounded, base, {session_id: `00000000-0000-4000-8000-${String(n).padStart(12,'0')}`, token: 'x'.repeat(43), device_id:key}, key, write, '2026-11-14T00:00:00.000Z');
assert.ok(new TextEncoder().encode(JSON.stringify(bounded)).length <= 2000);
const fullDisk = disk;
await assert.rejects(store.savePreferences(bounded, base, auth('overflow'), key, write, '2026-11-14T00:00:00.000Z'), /dossier_limit/);
assert.equal(disk, fullDisk, 'No silent eviction');
await assert.rejects(store.savePreferences(old, base, {...auth('oversize'), token: 'x'.repeat(2000)}, key, write, '2026-11-14T00:00:00.000Z'), /dossier_limit/);
assert.equal(disk, fullDisk, 'Byte cap checked before write');
console.log('PASS secure index legacy migration, retained references, write failure, host isolation, count/byte limits');
